    // Decryption scatters through kData2. A vector lookup needs the inverse gather indices.
    inline constexpr auto kInverseData2 = []
    {
        auto inverse = kData2;
        for (size_t table = 0; table < kData2.size(); ++table)
            for (size_t i = 0; i < 16; ++i)
                inverse[table][kData2[table][i]] = static_cast<uint8_t>(i);

        return inverse;
    }();

    struct XorSchedule
    {
        // The first 32 bytes include the initial key reset. The remaining 32 repeat.
        std::array<uint8_t, 64> bytes;

        XorSchedule(const std::array<uint8_t, 32>& key, uint32_t outputLength);

        [[nodiscard]] const uint8_t* block(const size_t offset) const noexcept
        {
            return bytes.data() + (offset < 32 ? offset : 32 + (offset & 31));
        }
    };

    /** Source and destination must be disjoint, equal-sized whole permutation blocks. */
    void decryptBlocks(std::span<const uint8_t> src, std::span<uint8_t> dst,
                       const XorSchedule& schedule, uint32_t outputLength);

    /** Encrypts padded whole permutation blocks in place. */
    void encryptBlocks(std::span<uint8_t> data, const XorSchedule& schedule, uint32_t outputLength);
